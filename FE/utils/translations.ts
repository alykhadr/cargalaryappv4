export const getLocaleFromLanguage = (language: string): SupportedLocale => {
    return language === 'Arabic' ? 'ar' : 'en';
};

const preserveOuterWhitespace = (source: string, translated: string) => {
    const leading = source.match(/^\s*/)?.[0] ?? '';
    const trailing = source.match(/\s*$/)?.[0] ?? '';

    return `${leading}${translated}${trailing}`;
};

const translateInterpolatedText = (text: string, dictionary: Record<string, string>) => {
    let nextText = text;

    Object.keys(dictionary)
        .sort((a, b) => b.length - a.length)
        .forEach((key) => {
            if (!nextText.includes(key)) {
                return;
            }

            nextText = nextText.split(key).join(dictionary[key]);
        });

    return nextText;
};

export const translateText = (value: string, locale: SupportedLocale) => {
    if (locale === 'en') {
        return value;
    }

    const trimmedValue = value.trim();

    if (!trimmedValue) {
        return value;
    }

    const dictionary = ar;
    const translated = dictionary[trimmedValue] ?? translateInterpolatedText(trimmedValue, dictionary);

    return preserveOuterWhitespace(value, translated);
};
